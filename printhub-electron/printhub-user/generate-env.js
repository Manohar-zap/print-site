// generate-env.js
// Writes `env.js` from environment variables (used by Vercel during build)
const fs = require('fs');
const path = require('path');

const env = {
  SUPABASE_URL: process.env.SUPABASE_URL || '',
  SUPABASE_ANON_KEY: process.env.SUPABASE_ANON_KEY || '',
  RAZORPAY_KEY: process.env.RAZORPAY_KEY || ''
};

const out = `// Auto-generated by generate-env.js — do NOT commit\nwindow.__ENV = ${JSON.stringify(env, null, 2)};\n`;
const outPath = path.join(__dirname, 'env.js');

try {
  fs.writeFileSync(outPath, out, 'utf8');
  console.log('Wrote', outPath);
} catch (err) {
  console.error('Failed to write env.js:', err);
  process.exit(1);
}

process.exit(0);
