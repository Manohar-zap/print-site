// Writes `env.js` and syncs static assets to `public/` so Vercel can deploy without missing output directory.
const fs = require('fs');
const path = require('path');

const env = {
  SUPABASE_URL: process.env.SUPABASE_URL || 'https://bqvcrsktjzivdvzodgab.supabase.co',
  SUPABASE_ANON_KEY: process.env.SUPABASE_ANON_KEY || 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImJxdmNyc2t0anppdmR2em9kZ2FiIiwicm9sZSI6ImFub24iLCJpYXQiOjE3Nzg5NDU1MzYsImV4cCI6MjA5NDUyMTUzNn0.Jq0rWvAkDyRcNov67Y6b6XsUBlAZwkIoWATvPIbsAGc',
  RAZORPAY_KEY: process.env.RAZORPAY_KEY || ''
};

const out = `// Auto-generated by generate-env.js — do NOT commit\nwindow.__ENV = ${JSON.stringify(env, null, 2)};\n`;

try {
  // Write env.js in current root
  const outPath = path.join(__dirname, 'env.js');
  fs.writeFileSync(outPath, out, 'utf8');
  console.log('Wrote', outPath);

  // Ensure public directory exists for Vercel Static Build
  const publicDir = path.join(__dirname, 'public');
  if (!fs.existsSync(publicDir)) {
    fs.mkdirSync(publicDir, { recursive: true });
  }
  fs.writeFileSync(path.join(publicDir, 'env.js'), out, 'utf8');

  // Copy web files into public
  const entries = fs.readdirSync(__dirname, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name === 'public' || entry.name === 'node_modules' || entry.name === '.git' || entry.name === 'printhub-electron') continue;
    const srcPath = path.join(__dirname, entry.name);
    const destPath = path.join(publicDir, entry.name);
    if (entry.isFile() && (entry.name.endsWith('.html') || entry.name.endsWith('.js') || entry.name.endsWith('.css') || entry.name.endsWith('.json') || entry.name.endsWith('.svg') || entry.name.endsWith('.png') || entry.name.endsWith('.ico'))) {
      fs.copyFileSync(srcPath, destPath);
    } else if (entry.isDirectory() && entry.name === 'src') {
      fs.cpSync(srcPath, destPath, { recursive: true });
    }
  }
  console.log('Populated public directory for Vercel static build at', publicDir);
} catch (err) {
  console.error('Failed to write env.js or build public directory:', err);
  process.exit(1);
}

process.exit(0);
